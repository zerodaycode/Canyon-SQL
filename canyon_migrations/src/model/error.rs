use std::fmt;

/// A model that can't be built: bad names or a table declared twice.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum ModelError {
    InvalidIdent(String),
    DuplicateColumn { table: String, column: String },
    DuplicateTable(String),
    KeyWithoutColumn { table: String },
    IdentityOnCompositeKey { table: String },
}

impl fmt::Display for ModelError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidIdent(name) => write!(
                f,
                "`{name}` is not a valid name: use letters, digits and `_`, start with a letter or `_`, at most 63 characters"
            ),
            Self::DuplicateColumn { table, column } => {
                write!(f, "{table}: column `{column}` is declared twice")
            }
            Self::DuplicateTable(table) => write!(f, "table `{table}` is declared by two entities"),
            Self::KeyWithoutColumn { table } => {
                write!(f, "{table}: a key was declared before any column")
            }
            Self::IdentityOnCompositeKey { table } => write!(
                f,
                "{table}: only a primary key of one column can be generated by the database"
            ),
        }
    }
}

impl std::error::Error for ModelError {}
